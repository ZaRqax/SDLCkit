#!/usr/bin/env bash
# apply-pipeline.sh — make the on-disk agent set match config/pipeline.yaml (the pipeline toggle).
#
#   bash scripts/apply-pipeline.sh                  reconcile + re-port pi/opencode + verify
#   bash scripts/apply-pipeline.sh --reconcile-only just flip the agent files (no re-port, no verify)
#   ./setup.sh --pipeline                           same as the full run (preferred entry point)
#
# How a toggle takes effect everywhere from one source:
#   * Claude reads .claude/agents/*.md directly — so a DISABLED agent's <name>.md is parked as
#     <name>.md.disabled (Claude only loads *.md). Re-enabling moves it back. Nothing is deleted.
#   * pi + opencode + qwen are GENERATED by the porters, which already skip disabled agents (and any
#     command bound only to a disabled agent). We re-run them and drop any stale generated file.
#   * Crush reads AGENTS.md prose only — no per-agent files to reconcile.
# Reversible: edit config/pipeline.yaml, re-run. The .md <-> .md.disabled rename shows up in git so
# your pipeline choices stay legible.
set -euo pipefail
KIT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$KIT_DIR"

bold() { printf '\033[1m%s\033[0m\n' "$1"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$1"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$1"; }
info() { printf '  • %s\n' "$1"; }

RECONCILE_ONLY=0
[ "${1:-}" = "--reconcile-only" ] && RECONCILE_ONLY=1
AGENTS_DIR=".claude/agents"

# Fail-open: with no parser or no config we must NEVER leave an agent silently disabled. Restore any
# parked <name>.md.disabled back to <name>.md (enable everything) and stop.
restore_all_parked() {
  for f in "$AGENTS_DIR"/*.md.disabled; do
    [ -e "$f" ] || continue
    base="$(basename "$f" .disabled)"   # -> <name>.md
    if [ ! -f "$AGENTS_DIR/$base" ]; then mv -f "$f" "$AGENTS_DIR/$base"; ok "restored $AGENTS_DIR/$base"
    else rm -f "$f"; fi
  done
}
if ! command -v python3 >/dev/null 2>&1; then
  warn "python3 not found — cannot read config/pipeline.yaml; restoring any parked agents (enable all)"
  restore_all_parked; exit 0
fi
if [ ! -f config/pipeline.yaml ]; then
  warn "config/pipeline.yaml not found — fail-open: restoring any parked agents (enable all)"
  restore_all_parked; exit 0
fi

pc() { python3 scripts/pipeline_config.py "$@" 2>/dev/null || true; }

# Validate first — refuse to apply a malformed config (it would mis-toggle agents).
if ! python3 scripts/pipeline_config.py check >/dev/null 2>&1; then
  warn "config/pipeline.yaml is invalid — fix it first:"; python3 scripts/pipeline_config.py check || true
  exit 1
fi

ENABLED="$(pc enabled)"
DISABLED="$(pc disabled)"

bold "Reconciling .claude/agents/ with config/pipeline.yaml"

# DISABLED agents: park <name>.md as <name>.md.disabled so Claude stops discovering it. We touch ONLY
# the Claude source here; the generated pi/opencode copies are regenerated wholesale in the re-port
# step below (skipped under --reconcile-only), so this stays safe to run before setup's own porting.
for d in $DISABLED; do
  if [ -f "$AGENTS_DIR/$d.md" ]; then
    mv -f "$AGENTS_DIR/$d.md" "$AGENTS_DIR/$d.md.disabled"
    warn "disabled $d → $AGENTS_DIR/$d.md.disabled"
  elif [ -f "$AGENTS_DIR/$d.md.disabled" ]; then
    info "$d already disabled"
  else
    warn "$d is disabled in config but no $AGENTS_DIR/$d.md[.disabled] file exists"
  fi
done

# ENABLED agents: restore <name>.md.disabled back to <name>.md.
for e in $ENABLED; do
  if [ -f "$AGENTS_DIR/$e.md.disabled" ] && [ ! -f "$AGENTS_DIR/$e.md" ]; then
    mv -f "$AGENTS_DIR/$e.md.disabled" "$AGENTS_DIR/$e.md"
    ok "enabled $e → $AGENTS_DIR/$e.md"
  elif [ -f "$AGENTS_DIR/$e.md.disabled" ] && [ -f "$AGENTS_DIR/$e.md" ]; then
    rm -f "$AGENTS_DIR/$e.md.disabled"   # both present: keep the active one
    info "$e active (removed stray .disabled duplicate)"
  elif [ ! -f "$AGENTS_DIR/$e.md" ]; then
    warn "$e is enabled in config but $AGENTS_DIR/$e.md is missing"
  fi
done

[ -n "$DISABLED" ] && info "disabled: $(echo "$DISABLED" | tr '\n' ' ')" || info "all agents enabled"

if [ "$RECONCILE_ONLY" -eq 1 ]; then
  ok "reconcile-only: agent files updated (re-port + verify skipped)"; exit 0
fi

# Regenerate the committed pi snapshot from the (now reconciled) source — no stale files left behind.
bold "Re-porting generated agents"
rm -f agents-config/pi/agents/*.md
if python3 agents-config/pi/port-agents.py >/dev/null 2>&1; then ok "pi snapshot → agents-config/pi/agents/"
else warn "port-agents.py failed — run it manually"; fi

# Only regenerate opencode if it was set up (the .opencode dir exists); it is gitignored.
if [ -d .opencode ]; then
  rm -f .opencode/agent/*.md .opencode/command/*.md
  if python3 agents-config/opencode/port-to-opencode.py .opencode >/dev/null 2>&1; then ok "opencode → .opencode/"
  else warn "port-to-opencode.py failed — run it manually"; fi
fi

# Only regenerate qwen if it was set up (the .qwen/agents dir exists); it is gitignored. Project
# .qwen/{agents,commands,skills} are fully generated (personal skills live in ~/.qwen/skills), so we
# regenerate them wholesale — there are never any hand edits to lose.
if [ -d .qwen/agents ]; then
  rm -f .qwen/agents/*.md .qwen/commands/*.md
  rm -rf .qwen/skills
  if python3 agents-config/qwen/port-to-qwen.py .qwen >/dev/null 2>&1; then ok "qwen → .qwen/"
  else warn "port-to-qwen.py failed — run it manually"; fi
fi

bold "Verifying"
bash scripts/check-kit.sh || true
echo
ok "pipeline applied. (Re-enable later by setting enabled: true in config/pipeline.yaml and re-running.)"
